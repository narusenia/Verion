#!/usr/bin/env python3
"""Writes crates/verion-gpu/tables/sheen_albedo.f32 (the table, little-endian float32) and shaders/include/sheen_albedo.slang (its size only): the directional albedo E(mu, r) of the sheen lobe
(Charlie distribution with the Neubelt visibility, color 1, alpha = r^2), used to attenuate the base
under a sheen layer (KHR_materials_sheen). The table is indexed [r][mu], both at N evenly spaced
nodes from 0 to 1; r is nudged to 0.07 (the shader's lower clamp) and mu = 0 to 0.01.
E = integral of D * V * cos(wi) over the hemisphere, done with quadrature uniform in the polar angle.
Usage: gen_sheen_albedo.py OUT_SLANG OUT_F32"""
import math, struct, sys

N = 16        # table nodes per axis
NU, NP = 1024, 64  # quadrature cells over the polar angle (the lobe peaks at grazing angles) and azimuth


def albedo(mu, r):
    a = r * r
    wo = (math.sqrt(1.0 - mu * mu), 0.0, mu)
    total = 0.0
    for i in range(NU):
        theta = (i + 0.5) / NU * (math.pi / 2)
        ci, si = math.cos(theta), math.sin(theta)
        for j in range(NP):
            phi = (j + 0.5) / NP * math.tau
            wi = (si * math.cos(phi), si * math.sin(phi), ci)
            h = [wo[k] + wi[k] for k in range(3)]
            n = math.sqrt(sum(c * c for c in h))
            hz = h[2] / n
            sin_h = math.sqrt(max(1.0 - hz * hz, 0.0))
            d = (2.0 + 1.0 / a) * sin_h ** (1.0 / a) / math.tau
            v = 1.0 / (4.0 * (ci + mu - ci * mu))
            total += d * v * ci * si  # D * V * cos(wi) * sin(theta)
    return min(total * (math.pi / 2 / NU) * (math.tau / NP), 1.0)


def main(path, table):
    rows = [[albedo(max(m / (N - 1), 0.01), max(r / (N - 1), 0.07)) for m in range(N)] for r in range(N)]
    flat = [float(f"{v:.6f}") for v in [v for row in rows for v in row]]  # rounded as before: the table is what the shader used to hold
    with open(table, "wb") as f:
        f.write(struct.pack(f"<{len(flat)}f", *flat))
    with open(path, "w") as f:
        f.write("// Generated by scripts/gen_sheen_albedo.py; do not edit.\n")
        f.write("// The table itself is crates/verion-gpu/tables/sheen_albedo.f32 (little-endian float32); the host\n")
        f.write("// uploads it into `lights` after the light table (see `albedoAt` in pt_core.slang).\n")
        f.write(f"static const uint SHEEN_ALBEDO_N = {N};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
