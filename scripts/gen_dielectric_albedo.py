#!/usr/bin/env python3
"""Writes crates/verion-gpu/tables/dielectric_albedo.f32 (the table, little-endian float32) and shaders/include/dielectric_albedo.slang (its size only): the single-scattering directional albedo E of a rough
dielectric interface (reflection plus transmission, GGX with the shader's alpha and separable Smith G),
used by the multiple-scattering compensation of rough transmission.
E is the mean, over visible normals, of F * G1(wi_reflected) + (1 - F) * G1(wi_transmitted), where a
direction below the surface for a reflection or a total internal reflection counts as 0. These are the
very weights the shader's sampler returns without its radiance factor (n_i / n_t)^2, which cancels when
the path leaves the medium, so 1 / E restores the energy of each interaction.
The table is indexed [side][ior][r][mu]: side 0 enters the medium (eta = ior), side 1 leaves it
(eta = 1 / ior); ior has N_IOR nodes from 1 to 3; r = sqrt(alpha) and mu = cos(theta_o) have N nodes
from 0 to 1 (mu = 0 is nudged to 0.01, alpha is floored at 1e-3 like the shader).
Usage: gen_dielectric_albedo.py OUT_SLANG OUT_F32"""
import math
import struct
import sys
from multiprocessing import Pool

N = 16           # nodes per axis for r and mu
N_IOR = 9        # ior = 1 + 0.25 * i
NS = 96          # stratified samples per axis over the visible-normal sampler's (u1, u2)


def g1(c, a):
    return 2.0 / (1.0 + math.sqrt(1.0 + a * a * (1.0 - c * c) / (c * c)))


def fresnel(cosi, eta):
    s2 = (1.0 - cosi * cosi) / (eta * eta)
    if s2 >= 1.0:
        return 1.0
    cost = math.sqrt(1.0 - s2)
    rs = (cosi - eta * cost) / (cosi + eta * cost)
    rp = (eta * cosi - cost) / (eta * cosi + cost)
    return 0.5 * (rs * rs + rp * rp)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def normalize(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def sample_vndf(wo, alpha, u1, u2):  # the shader's sampleVndf (Heitz 2018)
    vh = normalize((alpha * wo[0], alpha * wo[1], wo[2]))
    lensq = vh[0] ** 2 + vh[1] ** 2
    t1 = (-vh[1], vh[0], 0.0) if lensq > 0.0 else (1.0, 0.0, 0.0)
    if lensq > 0.0:
        k = 1.0 / math.sqrt(lensq)
        t1 = tuple(c * k for c in t1)
    t2 = cross(vh, t1)
    r = math.sqrt(u1)
    phi = math.tau * u2
    a, b = r * math.cos(phi), r * math.sin(phi)
    s = 0.5 * (1.0 + vh[2])
    b = (1.0 - s) * math.sqrt(1.0 - a * a) + s * b
    c = math.sqrt(max(0.0, 1.0 - a * a - b * b))
    nh = tuple(a * t1[i] + b * t2[i] + c * vh[i] for i in range(3))
    return normalize((alpha * nh[0], alpha * nh[1], max(0.0, nh[2])))


def albedo(args):
    side, i_ior, i_r, i_mu = args
    ior = 1.0 + 0.25 * i_ior
    eta = ior if side == 0 else 1.0 / ior
    alpha = max((i_r / (N - 1)) ** 2, 1.0e-3)
    mu = max(i_mu / (N - 1), 0.01)
    wo = (math.sqrt(1.0 - mu * mu), 0.0, mu)
    total = 0.0
    for i in range(NS):
        for j in range(NS):
            h = sample_vndf(wo, alpha, (i + 0.5) / NS, (j + 0.5) / NS)
            woh = sum(wo[k] * h[k] for k in range(3))
            f = fresnel(woh, eta)
            wi = tuple(2.0 * woh * h[k] - wo[k] for k in range(3))
            if wi[2] > 0.0:
                total += f * g1(wi[2], alpha)
            r = 1.0 / eta
            k = 1.0 - r * r * (1.0 - woh * woh)
            if k > 0.0:
                c = r * woh - math.sqrt(k)
                wt = tuple(-wo[m] * r + c * h[m] for m in range(3))
                if wt[2] < 0.0:
                    total += (1.0 - f) * g1(-wt[2], alpha)
    return min(total / (NS * NS), 1.0)


def main(path, table):
    jobs = [(s, a, r, m) for s in range(2) for a in range(N_IOR) for r in range(N) for m in range(N)]
    with Pool() as pool:
        values = pool.map(albedo, jobs, chunksize=64)
    flat = [float(f"{v:.5f}") for v in values]  # rounded as before: the table is what the shader used to hold
    with open(table, "wb") as f:
        f.write(struct.pack(f"<{len(flat)}f", *flat))
    with open(path, "w") as f:
        f.write("// Generated by scripts/gen_dielectric_albedo.py; do not edit.\n")
        f.write("// The table itself is crates/verion-gpu/tables/dielectric_albedo.f32 (little-endian float32); the host\n")
        f.write("// uploads it into `lights` after the light table (see `albedoAt` in pt_core.slang).\n")
        f.write(f"static const uint DIEL_ALBEDO_N = {N};\n")
        f.write(f"static const uint DIEL_ALBEDO_N_IOR = {N_IOR};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
