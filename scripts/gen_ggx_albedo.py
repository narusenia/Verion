#!/usr/bin/env python3
"""Writes shaders/include/ggx_albedo.slang: the single-scattering GGX directional albedo E(mu, alpha)
for F = 1, with the shader's alpha and separable Smith G, used by the multiple-scattering
compensation of rough metals. The table is indexed [r][mu] with r = sqrt(alpha) and mu = cos(theta_o),
both at N evenly spaced nodes from 0 to 1 (r = 0 is a mirror, E = 1; mu = 0 is nudged to 0.01).
E is the mean of G1(wi) over visible normals, so it is integrated over the GGX-distributed half
vector. Usage: gen_ggx_albedo.py OUT_FILE"""
import math, sys

N = 32          # table nodes per axis
NU = NP = 256   # quadrature cells over the half-vector distribution


def g1(c, a):
    return 2.0 / (1.0 + math.sqrt(1.0 + a * a * (1.0 - c * c) / (c * c)))


def albedo(mu, a):
    if a == 0.0:
        return 1.0
    wo = (math.sqrt(1.0 - mu * mu), 0.0, mu)
    total = 0.0
    for i in range(NU):
        u = (i + 0.5) / NU                         # GGX CDF of the half-vector polar angle
        tan2 = a * a * u / (1.0 - u)
        cos_h = 1.0 / math.sqrt(1.0 + tan2)
        sin_h = math.sqrt(1.0 - cos_h * cos_h)
        for j in range(NP):
            phi = (j + 0.5) / NP * math.tau
            h = (sin_h * math.cos(phi), sin_h * math.sin(phi), cos_h)
            woh = wo[0] * h[0] + wo[1] * h[1] + wo[2] * h[2]
            if woh <= 0.0:
                continue
            wiz = 2.0 * woh * h[2] - wo[2]
            if wiz <= 0.0:
                continue
            # (visible-normal weight) / (D cos_h): G1(wo) * woh / (wo.z * cos_h), times G1(wi).
            total += g1(mu, a) * woh / (mu * cos_h) * g1(wiz, a)
    return min(total / (NU * NP), 1.0)


def main(path):
    rows = []
    for r in range(N):
        a = (r / (N - 1)) ** 2
        rows.append([albedo(max(m / (N - 1), 0.01), a) for m in range(N)])
    with open(path, "w") as f:
        f.write("// Generated by scripts/gen_ggx_albedo.py; do not edit.\n")
        f.write(f"static const uint GGX_ALBEDO_N = {N};\n")
        f.write(f"static const float GGX_ALBEDO[{N * N}] = {{\n")
        for row in rows:
            f.write("    " + ", ".join(f"{v:.6f}" for v in row) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1])
